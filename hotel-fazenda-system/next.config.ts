import type { NextConfig } from "next";
import withSerwistInit from "@serwist/next";

const withSerwist = withSerwistInit({
  swSrc: "app/sw.ts",
  swDest: "public/sw.js",
  // Auto-cache of navigation responses is OFF: authenticated pages may carry
  // per-user data, so we let sw.ts decide what gets cached.
  cacheOnNavigation: false,
  reloadOnOnline: false,
  // Disable SW in dev to avoid HMR caching surprises. Build/start in PROD
  // (or `next dev` with NEXT_PWA_SW=1) registers the worker.
  disable: process.env.NODE_ENV === "development",
});

const securityHeaders = [
  { key: "Strict-Transport-Security", value: "max-age=63072000; includeSubDomains; preload" },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=(), interest-cohort=()" },
  // Conservative baseline. Next.js inlines styles and scripts; we allow self
  // + 'unsafe-inline' for styles (required by Tailwind/Next) and limit
  // connect-src to Supabase. Tighten with nonces in a follow-up sprint once
  // Server Components stop emitting inline boot scripts.
  {
    key: "Content-Security-Policy",
    value: [
      "default-src 'self'",
      "script-src 'self' 'unsafe-inline' 'unsafe-eval'",
      "style-src 'self' 'unsafe-inline'",
      "img-src 'self' data: blob: https:",
      "font-src 'self' data:",
      "connect-src 'self' https://*.supabase.co wss://*.supabase.co",
      "frame-ancestors 'none'",
      "base-uri 'self'",
      "form-action 'self'",
    ].join("; "),
  },
];

const nextConfig: NextConfig = {
  async headers() {
    return [
      {
        source: "/:path*",
        headers: securityHeaders,
      },
    ];
  },
};

export default withSerwist(nextConfig);
